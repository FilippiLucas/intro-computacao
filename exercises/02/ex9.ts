console.log("Math.ceil() retorna o menor inteiro maior ou igual ao input.");
console.log("Ex: 10.25" + "\n" + "Resultado = " + Math.ceil(10.25) + "\n");

console.log("Math.floor() retorna o maior inteiro menor ou igual ao input.");
console.log("Ex: 10.25" + "\n" + "Resultado = " + Math.floor(10.25) + "\n");

console.log("Math.round() retorna o valor do input arredondado para o inteiro mais proximo.");
console.log("Ex: 10.25" + "\n" + "Resultado = " + Math.round(10.25) + "\n");

console.log("Math.trunc() retorna a parte inteira de um input, removendo a parte decimal");
console.log("Ex: 10.25" + "\n" + "Resultado = " + Math.trunc(10.25) + "\n");
